print("Hello, World!")

num1 = input('Digite um valor')
print(f"Só tem espaços? {num1.isspace()}")
print(f"Está em maiúsculo?? {num1.isupper()}")
print(f"Está em minúsculo?? {num1.islower()}")
print(f"Está alfabetizada?? {num1.isalpha()}")
print(f"Está alfanumérico?? {num1.isalnum()}")
print(f'O tipo desse valor é: {type(num1)}')